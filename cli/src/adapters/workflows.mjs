/** @typedef {import("../types.js").CommandKey} CommandKey */
/** @typedef {import("../types.js").Profile} Profile */
import { exists, readFile, writeFile, writeIfMissing } from "../lib/fs-tools.mjs";
import { sourceEnv, installStep } from "./esteira-source.mjs";

const step = (/** @type {string} */ name, /** @type {string} */ run) => `      - name: ${name}\n        run: ${run}`;
const uses = (/** @type {string} */ action, withBlock = "") =>
  withBlock ? `      - uses: ${action}\n        with:\n${withBlock}` : `      - uses: ${action}`;

/** @param {Pick<Profile, "languages" | "subprojects">} profile */
function setupSteps(profile) {
  /** @type {string[]} */
  const steps = [];
  const stacks = [...profile.languages, ...(profile.subprojects ?? []).flatMap((p) => p.languages)];
  for (const lang of stacks) {
    switch (lang.id) {
      case "node":
        if (lang.packageManager === "pnpm") {
          steps.push(uses("pnpm/action-setup@v4", "          version: 9"));
        }
        steps.push(uses("actions/setup-node@v4", `          node-version: '${lang.runtime.node ?? "20"}'`));
        break;
      case "python":
        steps.push(uses("actions/setup-python@v5", "          python-version: '3.x'"));
        break;
      case "go":
        steps.push(uses("actions/setup-go@v5", `          go-version: '${lang.runtime.go ?? "1.22"}'`));
        break;
      case "rust":
        steps.push(uses("dtolnay/rust-toolchain@stable"));
        break;
      case "jvm":
        steps.push(uses("actions/setup-java@v4", "          distribution: temurin\n          java-version: '21'"));
        break;
      case "dotnet":
        steps.push(uses("actions/setup-dotnet@v4", "          dotnet-version: '8.0.x'"));
        break;
      case "ruby":
        steps.push(uses("ruby/setup-ruby@v1", "          ruby-version: '3.3'"));
        break;
      case "php":
        steps.push(uses("shivammathur/setup-php@v2", "          php-version: '8.3'"));
        break;
    }
    if (lang.installCommand) steps.push(step("Instalar dependências", lang.installCommand));
  }
  return steps;
}

/** @param {Pick<Profile, "languages" | "subprojects" | "commands">} profile */
export function renderWorkflow(profile) {
  const steps = ["      - uses: actions/checkout@v4", ...setupSteps(profile)];
  /** @type {Record<CommandKey, string>} */
  const labels = { lint: "Lint", typecheck: "Typecheck", test: "Test", build: "Build" };
  for (const key of /** @type {CommandKey[]} */ (["lint", "typecheck", "test", "build"])) {
    const cmd = profile.commands[key];
    if (cmd) steps.push(step(labels[key], cmd));
  }

  return `# Generated by \`gh esteira init\`. Edit freely; use --force to regenerate.
# TODO(M5): pin every action to a verified full commit SHA.
name: Esteira CI
on:
  pull_request:
  push:
    branches: [main]
permissions:
  contents: read
concurrency:
  group: esteira-${"${{ github.ref }}"}
  cancel-in-progress: true

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
${steps.join("\n")}

  # Authoritative gate (S1/S5): local hooks and .esteira/runs records can be
  # bypassed (--no-verify) or forged, so the same gate runs here on the change
  # set. Make this job a required status check in branch protection.
  security-gate:
    runs-on: ubuntu-latest
    env:
${sourceEnv("      ")}      BASE_SHA: ${"${{ github.event.pull_request.base.sha || github.event.before }}"}
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: '22'
${installStep}      # Stage everything since the base so \`gate\` judges the whole change set.
      # A push that creates a branch sends before=0000…: compare with HEAD~1 then.
      - name: Stage the change set against its base
        run: |
          CHANGE_BASE="$BASE_SHA"
          case "$CHANGE_BASE" in ''|*[!0]*) ;; *) CHANGE_BASE="" ;; esac
          if [ -z "$CHANGE_BASE" ] && git rev-parse --verify -q HEAD~1 >/dev/null 2>&1; then CHANGE_BASE="$(git rev-parse HEAD~1)"; fi
          if [ -z "$CHANGE_BASE" ] || ! git cat-file -e "$CHANGE_BASE^{commit}" 2>/dev/null; then
            echo "::error::Sem commit base para comparar (BASE_SHA='$BASE_SHA')"; exit 1
          fi
          echo "CHANGE_BASE=$CHANGE_BASE" >> "$GITHUB_ENV"
          git reset --soft "$CHANGE_BASE"
      # Policy comes from the base commit, never from the PR being judged.
      - name: Esteira gate (server-side)
        run: node "$ESTEIRA" gate --policy-ref "$CHANGE_BASE"
`;
}

const WORKFLOW_REL = ".github/workflows/esteira-ci.yml";
const GENERATED_HEADER = "# Generated by `gh esteira init`";

/**
 * Writes the CI workflow. `force` overwrites it. `refresh` (used by update)
 * regenerates only a workflow the esteira generated and that is out of date; the
 * previous content goes to .esteira/backups first. A hand-written workflow is never touched.
 * @param {string} root @param {Profile} profile @param {{ force?: boolean, refresh?: boolean }} [options]
 */
export function writeWorkflow(root, profile, { force = false, refresh = false } = {}) {
  const rendered = renderWorkflow(profile);
  if (exists(root, WORKFLOW_REL)) {
    const current = readFile(root, WORKFLOW_REL) ?? "";
    if (force) {
      writeFile(root, WORKFLOW_REL, rendered);
      return { path: WORKFLOW_REL, written: true, reason: "regenerated" };
    }
    if (refresh && current.startsWith(GENERATED_HEADER) && current !== rendered) {
      const backup = backupWorkflow(root, current);
      writeFile(root, WORKFLOW_REL, rendered);
      return { path: WORKFLOW_REL, written: true, reason: "regenerated", backup };
    }
  }
  const result = writeIfMissing(root, WORKFLOW_REL, rendered);
  return { path: WORKFLOW_REL, written: result.written, reason: result.reason };
}

/** @param {string} root @param {string} content @returns {string} backup path */
function backupWorkflow(root, content) {
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const rel = `.esteira/backups/esteira-ci.yml.${stamp}`;
  writeFile(root, rel, content);
  return rel;
}
