/**
 * Build & publish workflow: OCI image tagged by the immutable commit SHA,
 * with SBOM + provenance attestations on by default, then a Trivy scan and a
 * promotion PR to the GitOps repo. No job holds cluster credentials; the
 * cluster is reconciled by Argo CD from the GitOps repo.
 */
/** @param {{ app: string, registry?: string, gitopsRepo?: string }} input */
export function renderReleaseWorkflow({ app, registry = "ghcr.io", gitopsRepo = "REPLACE-ME/esteira-gitops" }) {
  return `# Generated by \`gh esteira gitops\`. Edit freely; use --force to regenerate.
# Run \`gh esteira pin\` after this lands to SHA-pin every action below.
name: Esteira release
on:
  push:
    branches: [main]
    tags: ["v*"]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: esteira-release-\${{ github.ref }}
  cancel-in-progress: false

env:
  APP: ${app}
  REGISTRY: ${registry}
  GITOPS_REPO: ${gitopsRepo}
  ESTEIRA_EXT: REPLACE-ME/gh-esteira # repo that publishes the gh-esteira extension

jobs:
  build-publish:
    # packages:write is scoped to the only job that needs it (README §7).
    permissions:
      contents: read
      packages: write
      id-token: write
    runs-on: ubuntu-latest
    outputs:
      image: \${{ env.REGISTRY }}/\${{ env.APP }}:\${{ github.sha }}
      published: \${{ steps.detect.outputs.skip != 'true' }}
    steps:
      - uses: actions/checkout@v4

      - name: Detect containerfile
        id: detect
        run: |
          if [ -f Dockerfile ]; then echo "dockerfile=Dockerfile" >> "$GITHUB_OUTPUT"; exit 0; fi
          if [ -f Containerfile ]; then echo "dockerfile=Containerfile" >> "$GITHUB_OUTPUT"; exit 0; fi
          echo "::notice::No Dockerfile/Containerfile found — publishing skipped"
          echo "skip=true" >> "$GITHUB_OUTPUT"

      - name: Log in to the registry
        if: \${{ steps.detect.outputs.skip != 'true' }}
        run: echo "\${{ secrets.GITHUB_TOKEN }}" | docker login \${{ env.REGISTRY }} -u \${{ github.actor }} --password-stdin

      # Image tag = immutable commit SHA; labels for readability only.
      - name: Build, SBOM + provenance, push
        if: \${{ steps.detect.outputs.skip != 'true' }}
        uses: docker/build-push-action@v6
        with:
          context: .
          file: \${{ steps.detect.outputs.dockerfile }}
          push: true
          provenance: mode=max
          sbom: true
          tags: |
            \${{ env.REGISTRY }}/\${{ env.APP }}:\${{ github.sha }}
          labels: |
            org.opencontainers.image.revision=\${{ github.sha }}
            org.opencontainers.image.source=\${{ github.server_url }}/\${{ github.repository }}

  image-scan:
    needs: build-publish
    if: \${{ needs.build-publish.outputs.published == 'true' }}
    permissions:
      contents: read
      packages: read
    runs-on: ubuntu-latest
    steps:
      - name: Log in to the registry
        run: echo "\${{ secrets.GITHUB_TOKEN }}" | docker login \${{ env.REGISTRY }} -u \${{ github.actor }} --password-stdin

      # Fails the release on HIGH/CRITICAL findings that already have a fix.
      - name: Trivy image scan
        uses: aquasecurity/trivy-action@0.28.0
        with:
          image-ref: \${{ needs.build-publish.outputs.image }}
          severity: HIGH,CRITICAL
          ignore-unfixed: true
          exit-code: "1"

  promote-staging:
    needs: [build-publish, image-scan]
    if: \${{ github.ref == 'refs/heads/main' }}
    permissions:
      contents: read
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      # GH_TOKEN needs write access to the GitOps repo (PR only; no cluster credentials).
      - name: Open GitOps promotion PR (staging)
        env:
          GH_TOKEN: \${{ secrets.GITOPS_TOKEN }}
        run: |
          gh extension install "\${{ env.ESTEIRA_EXT }}" || true
          gh esteira promote --env staging --tag "\${{ github.sha }}" --repo "\${{ env.GITOPS_REPO }}"

  # Production promotion is manual: run this workflow via workflow_dispatch from a tag,
  # behind a protected environment with required reviewers.
  promote-production:
    needs: [build-publish, image-scan]
    if: \${{ startsWith(github.ref, 'refs/tags/v') }}
    environment: production
    permissions:
      contents: read
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Open GitOps promotion PR (production)
        env:
          GH_TOKEN: \${{ secrets.GITOPS_TOKEN }}
        run: |
          gh extension install "\${{ env.ESTEIRA_EXT }}" || true
          gh esteira promote --env production --tag "\${{ github.sha }}" --repo "\${{ env.GITOPS_REPO }}"
`;
}
