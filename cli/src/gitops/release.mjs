/**
 * Build & publish workflow: OCI image tagged by the immutable commit SHA,
 * with SBOM + provenance attestations on by default. This workflow only
 * *publishes*; the cluster is reconciled by Argo CD from the GitOps repo.
 */
export function renderReleaseWorkflow({ app, registry = "ghcr.io" }) {
  return `# Generated by \`gh esteira gitops\`. Edit freely; use --force to regenerate.
# TODO(M5 audit): run \`gh esteira pin\` after this lands to SHA-pin every action below.
name: Esteira release
on:
  push:
    branches: [main]
    tags: ["v*"]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: esteira-release-\${{ github.ref }}"}
  cancel-in-progress: false

env:
  APP: ${app}
  REGISTRY: ${registry}

jobs:
  build-publish:
    # packages:write is scoped to the only job that needs it (README §7).
    permissions:
      contents: read
      packages: write
      id-token: write
    runs-on: ubuntu-latest
    outputs:
      image: \${{ env.REGISTRY }}"}/\${{ env.APP }}"}:\${{ github.sha }}"}
    steps:
      - uses: actions/checkout@v4

      - name: Detect containerfile
        id: detect
        run: |
          if [ -f Dockerfile ]; then echo "dockerfile=Dockerfile" >> "$GITHUB_OUTPUT"; exit 0; fi
          if [ -f Containerfile ]; then echo "dockerfile=Containerfile" >> "$GITHUB_OUTPUT"; exit 0; fi
          echo "::notice::No Dockerfile/Containerfile found — publishing skipped"
          echo "skip=true" >> "$GITHUB_OUTPUT"

      - name: Log in to the registry
        if: \${{ steps.detect.outputs.skip != 'true' }}"}
        run: echo "\${{ secrets.GITHUB_TOKEN }}"}" | docker login \${{ env.REGISTRY }}"} -u \${{ github.actor }}"} --password-stdin

      # Image tag = immutable commit SHA; tags/labels for readability only.
      - name: Build, sign-less SBOM + provenance, push
        if: \${{ steps.detect.outputs.skip != 'true' }}"}
        uses: docker/build-push-action@v6
        with:
          context: .
          file: \${{ steps.detect.outputs.dockerfile }}"}
          push: true
          provenance: mode=max
          sbom: true
          tags: |
            \${{ env.REGISTRY }}"}/\${{ env.APP }}"}:\${{ github.sha }}"}
          labels: |
            org.opencontainers.image.revision=\${{ github.sha }}"}
            org.opencontainers.image.source=\${{ github.server_url }}}/\${{ github.repository }}"}

  # TODO(M6): post-deploy smoke tests + image scan job (trivy) triggered from Argo CD.
`;
}
