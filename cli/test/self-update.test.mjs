// `gh esteira update` brings the extension to the latest tag, and regenerates
// only the workflows the esteira generated. `gh` is faked: no network here.
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { compareVersions, highestTag, installedVersion, latestVersion, newerVersionAvailable, upgradeExtension } from "../src/commands/self-update.mjs";
import { writeWorkflow } from "../src/adapters/workflows.mjs";

process.env.ESTEIRA_LLM_ENABLED = "false";

test("versions compare by semver and the highest tag wins", () => {
  assert.ok(compareVersions("v0.2.2", "v0.2.1") > 0);
  assert.ok(compareVersions("0.10.0", "0.9.9") > 0, "numeric, not lexical");
  assert.equal(compareVersions("v1.0.0", "1.0.0"), 0);
  assert.equal(highestTag(["v0.2.1", "nightly", "v0.10.0", "v0.9.0"]), "v0.10.0");
  assert.equal(highestTag(["main", "dev"]), null);
});

/** Fake `gh`: `tags` is what the API answers; `upgradeWorks` decides whether `extension upgrade` moves the version. */
function fakeGh({ tags = "v0.2.2\nv0.2.1\n", upgradeWorks = false, apiFails = false, installOk = true } = {}) {
  const state = { version: "v0.2.1", calls: [] };
  const gh = (args) => {
    state.calls.push(args.join(" "));
    if (args[0] === "api") return apiFails ? { status: 1, stdout: "" } : { status: 0, stdout: tags };
    if (args[0] === "esteira") return { status: 0, stdout: `${state.version}\n` };
    if (args[1] === "upgrade") { if (upgradeWorks) state.version = "v0.2.2"; return { status: 0, stdout: "" }; }
    if (args[1] === "remove") return { status: 0, stdout: "" };
    if (args[1] === "install") { if (installOk) state.version = args[args.indexOf("--pin") + 1]; return { status: installOk ? 0 : 1, stdout: "" }; }
    return { status: 1, stdout: "" };
  };
  return { gh, state };
}

test("latestVersion reads the tags; offline means no target", () => {
  assert.equal(latestVersion(fakeGh().gh), "v0.2.2");
  assert.equal(latestVersion(fakeGh({ apiFails: true }).gh), null);
  assert.equal(newerVersionAvailable("v0.2.2", fakeGh().gh), null, "already current");
  assert.equal(newerVersionAvailable("v0.2.1", fakeGh().gh), "v0.2.2");
  assert.equal(newerVersionAvailable("v0.2.1", fakeGh({ apiFails: true }).gh), null, "offline: keep running");
});

test("upgrade: an unpinned extension is upgraded in place", () => {
  const { gh, state } = fakeGh({ upgradeWorks: true });
  const out = upgradeExtension("v0.2.2", gh);
  assert.deepEqual(out, { ok: true, method: "upgrade", version: "v0.2.2" });
  assert.equal(state.calls.some((c) => c.includes("remove")), false, "no reinstall needed");
});

test("upgrade: a pinned extension is reinstalled pinned to the new tag", () => {
  const { gh } = fakeGh({ upgradeWorks: false });
  const out = upgradeExtension("v0.2.2", gh);
  assert.deepEqual(out, { ok: true, method: "reinstall-pinned", version: "v0.2.2" });
});

test("the installed version is compared in tag form (the CLI prints 0.2.1, tags are v0.2.1)", () => {
  const gh = (args) => (args[0] === "esteira" ? { status: 0, stdout: "0.2.2\n" } : { status: 1, stdout: "" });
  assert.equal(installedVersion(gh), "v0.2.2");
  const upgraded = upgradeExtension("v0.2.2", (args) => (args[0] === "esteira" ? { status: 0, stdout: "0.2.2\n" } : { status: 0, stdout: "" }));
  assert.equal(upgraded.method, "upgrade");
});

test("upgrade reports failure when the reinstall does not land", () => {
  const { gh } = fakeGh({ installOk: false });
  assert.equal(upgradeExtension("v0.2.2", gh).ok, false);
});

// --- workflow refresh ---

const git = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
function umbrellaRepo() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "esteira-refresh-"));
  git(dir, "init", "-q", "-b", "main");
  fs.mkdirSync(path.join(dir, "cli"));
  fs.writeFileSync(path.join(dir, "cli", "package.json"), JSON.stringify({ name: "c", version: "1.0.0", scripts: { test: "node --test" } }));
  return dir;
}
const profile = (dir) => ({
  root: dir, languages: [], subprojects: [{ path: "cli", gitRepo: false, languages: [{ id: "node", packageManager: null, runtime: {}, commands: { test: "npm run test" }, installCommand: null }] }],
  commands: { lint: null, typecheck: null, test: "npm --prefix cli run test", build: null },
});

test("update regenerates a generated workflow that is out of date, keeping a backup", () => {
  const dir = umbrellaRepo();
  const wfDir = path.join(dir, ".github", "workflows");
  fs.mkdirSync(wfDir, { recursive: true });
  const old = "# Generated by `gh esteira init`. Edit freely; use --force to regenerate.\nname: old\n";
  fs.writeFileSync(path.join(wfDir, "esteira-ci.yml"), old);
  const result = writeWorkflow(dir, profile(dir), { refresh: true });
  assert.equal(result.reason, "regenerated");
  assert.match(fs.readFileSync(path.join(wfDir, "esteira-ci.yml"), "utf8"), /npm --prefix cli run test/);
  assert.equal(fs.readFileSync(path.join(dir, result.backup), "utf8"), old, "previous content is kept");
});

test("update never rewrites a hand-written workflow", () => {
  const dir = umbrellaRepo();
  const wfDir = path.join(dir, ".github", "workflows");
  fs.mkdirSync(wfDir, { recursive: true });
  const handmade = "name: meu CI\non: push\n";
  fs.writeFileSync(path.join(wfDir, "esteira-ci.yml"), handmade);
  const result = writeWorkflow(dir, profile(dir), { refresh: true });
  assert.equal(result.reason, "exists");
  assert.equal(fs.readFileSync(path.join(wfDir, "esteira-ci.yml"), "utf8"), handmade);
});
